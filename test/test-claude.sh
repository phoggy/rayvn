#!/usr/bin/env bash

main() {
    init "$@"

    testProjectsTable
    testProjectsTableNoneFound
    testRenderReplacesPlaceholders
    testUpdateWritesOnlyWhenChanged

    return 0
}

init() {
    while (( $# )); do
        case "$1" in
            --debug*) setDebug "$@"; shift $? ;;
        esac
        shift
    done

    # Two fake project checkouts: 'alpha' with a pages worktree, 'beta' without one.

    declare -g testRoot; testRoot="${ makeTempDir; }"
    testRoot="${ cd "${testRoot}" && pwd -P; }"
    newFakeProject alpha "A first project." "../alpha-pages"
    mkdir "${testRoot}/alpha-pages" || fail
    newFakeProject beta "A second project."
    # Keep the directories of tools that rayvn needs (e.g. gsed, gawk), which hold no rayvn projects

    declare -g toolPath; toolPath="${ dirname "${ command -v gsed; }"; }:${ dirname "${ command -v gawk; }"; }:/usr/bin:/bin"
    declare -g testPath="${testRoot}/beta/bin:${toolPath}:${testRoot}/alpha/bin:${testRoot}/alpha/bin"

    # Never touch the real guide

    declare -g testGuideFile="${testRoot}/claude-rayvn.md"
    claudeGuideFile() { echo "${testGuideFile}"; }
}

newFakeProject() {
    local name="$1" description="$2" docsWorktree="${3:-}"
    mkdir -p "${testRoot}/${name}/bin" || fail
    printf "projectName='%s'\nprojectDescription='%s'\ndocsWorktree='%s'\n" "${name}" "${description}" "${docsWorktree}" \
        > "${testRoot}/${name}/rayvn.pkg"
}

testProjectsTable() {
    local table; table="${ PATH="${testPath}" _claudeGuideProjectsTable; }"
    local -a lines; mapfile -t lines <<< "${table}"
    assertEqual 4 "${#lines[@]}" "header, separator and one row per project (duplicates on PATH listed once): ${table}"
    assertEqual "| alpha | \`${testRoot}/alpha\` | \`${testRoot}/alpha-pages\` | A first project. |" "${lines[2]}"
    assertEqual "| beta | \`${testRoot}/beta\` | — | A second project. |" "${lines[3]}"
}

testProjectsTableNoneFound() {
    local table; table="${ PATH="${toolPath}" _claudeGuideProjectsTable; }"
    assertContains "None found" "${table}"
}

testRenderReplacesPlaceholders() {
    local guide; PATH="${testPath}" _renderClaudeGuide guide
    assertContains "Generated by ${ projectVersion rayvn; } from ${rayvnHome}/etc/claude/rayvn.md" "${guide}"
    assertContains "| beta |" "${guide}"
    assertContains "rayvn itself is at \`${rayvnHome}\`" "${guide}"
    assertContains "\`${ configDirPath -p rayvn; }/rayvn-functions-compact.txt\`" "${guide}"
    local placeholder
    for placeholder in rayvnGuideProjects rayvnHome rayvnConfigDir; do
        [[ ${guide} != *"\${${placeholder}}"* ]] || fail "placeholder \${${placeholder}} was not replaced"
    done
}

testUpdateWritesOnlyWhenChanged() {
    rm -f "${testGuideFile}"
    local output; output="${ PATH="${testPath}" updateClaudeGuide; }"
    assertContains "Updated Claude guide" "${output}"
    assertFile "${testGuideFile}"

    output="${ PATH="${testPath}" updateClaudeGuide; }"
    assertContains "Claude guide is current" "${output}"

    output="${ PATH="${testRoot}/alpha/bin:${toolPath}" updateClaudeGuide; }"
    assertContains "Updated Claude guide" "${output}" "a change in the projects on PATH must update the guide"
    assertNotInFile "| beta |" "${testGuideFile}"

    output="${ PATH="${testPath}" updateClaudeGuide -q; }"
    assertEqual '' "${output}" "--quiet must not report"
}

rayvnTest_ModifiableFunctions=1
source rayvn.up 'rayvn/test' 'rayvn/claude'
main "$@"
