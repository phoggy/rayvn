#!/usr/bin/env bash

# Guide for Claude Code to working with rayvn projects.
# Use via: require 'rayvn/claude'

# ◇ Render the rayvn guide for Claude Code into the rayvn config directory, from etc/claude/rayvn.md with a table of
#   the rayvn projects on this system (development checkouts whose bin directory is on PATH). The file is only written
#   when its content changes, so this is cheap to call often. A project's CLAUDE.md loads the guide with an import:
#   @~/.config/rayvn/claude-rayvn.md
#
# · USAGE
#
#   updateClaudeGuide [-q]
#
#   -q, --quiet  Do not report whether the guide was updated.

updateClaudeGuide() {
    local quiet=0
    [[ $1 == -q || $1 == --quiet ]] && quiet=1

    local guideFile; guideFile="${ claudeGuideFile; }"
    local guide; _renderClaudeGuide guide
    local current=''
    [[ -f "${guideFile}" ]] && readFile -p "${guideFile}" current
    if [[ "${guide}" == "${current}" ]]; then
        (( quiet )) || show "Claude guide is current:" blue "${ tildePath "${guideFile}"; }"
        return 0
    fi

    local tempFile="${guideFile}.tmp"
    printf '%s' "${guide}" > "${tempFile}" || fail "could not write ${tempFile}"
    mv -f "${tempFile}" "${guideFile}" || fail "could not write ${guideFile}"
    (( quiet )) || show "Updated Claude guide:" blue "${ tildePath "${guideFile}"; }"
    return 0
}

# ◇ Output the path of the rendered rayvn guide for Claude Code.

claudeGuideFile() {
    configDirPath -p rayvn 'claude-rayvn.md'
}

PRIVATE_CODE="--+-+-----+-++(-++(---++++(---+( ⚠️ BEGIN 'rayvn/claude' PRIVATE ⚠️ )+---)++++---)++-)++-+------+-+--"

_init_rayvn_claude() {
    declare -gr _claudeGuideTemplate="${rayvnHome}/etc/claude/rayvn.md"
}

# Render the guide into the named var.

_renderClaudeGuide() {
    local -n _rcgResultRef=$1
    local template; readFile -p "${_claudeGuideTemplate}" template
    local projects; projects="${ _claudeGuideProjectsTable; }"
    local configDir; configDir="${ configDirPath -p rayvn; }"

    template="${template//'${rayvnGuideProjects}'/${projects}}"
    template="${template//'${rayvnHome}'/${rayvnHome}}"
    template="${template//'${rayvnConfigDir}'/${configDir}}"
    _rcgResultRef="<!-- Generated by rayvn from ${_claudeGuideTemplate}: edit that file, not this one. -->"$'\n\n'"${template}"
}

# Output a markdown table of the rayvn projects whose bin directory is on PATH, with their root, pages worktree and
# description from rayvn.pkg.

_claudeGuideProjectsTable() {
    local -A seen=()
    local -a rows=()
    local dir root name description docsWorktree pages
    local -a pathDirs; IFS=':' read -ra pathDirs <<< "${PATH}"
    for dir in "${pathDirs[@]}"; do
        [[ -n "${dir}" && -f "${dir}/../rayvn.pkg" ]] || continue
        root="${ cd "${dir}/.." && pwd -P; }" || continue
        [[ -v seen[${root}] ]] && continue
        seen[${root}]=1

        name='' description='' docsWorktree=''
        IFS=$'\t' read -r name description docsWorktree < <(
            source "${root}/rayvn.pkg" 2> /dev/null
            printf '%s\t%s\t%s\n' "${projectName:-}" "${projectDescription:-}" "${docsWorktree:-}"
        )
        [[ -n "${name}" ]] || name="${root##*/}"
        pages="${docsWorktree:-../${name}-pages}"
        [[ "${pages}" == /* ]] || pages="${root}/${pages}"
        if [[ -d "${pages}" ]]; then
            pages="\`${ cd "${pages}" && pwd -P; }\`"
        else
            pages='—'
        fi
        rows+=("| ${name} | \`${root}\` | ${pages} | ${description:-—} |")
    done

    if (( ${#rows[@]} == 0 )); then
        echo "None found: add the bin directory of each rayvn project checkout to PATH, then run 'rayvn index --claude'."
        return 0
    fi
    echo '| Project | Root | Pages worktree | Description |'
    echo '|---|---|---|---|'
    printf '%s\n' "${rows[@]}" | sort
}
